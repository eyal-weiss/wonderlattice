<p>דרך אחרת היא להיפגש שוב ושוב. בטורנירים של רוברט אקסלרוד במשחק החוזר, בסביבות 1980, ההצעה הפשוטה ביותר, ”מידה כנגד מידה” של אנטול רפופורט (לשתף פעולה בפעם הראשונה, ואחר כך להעתיק את המהלך האחרון של השחקן השני), ניצחה בשני הסבבים. זה לא הופך אותה לאסטרטגיה הטובה ביותר: כשיש טעויות ויריבים שונים, הדירוג משתנה. <em>The Evolution of Trust</em> של ניקי קייס מספר את הסיפור הזה יפה מאוד.</p>
