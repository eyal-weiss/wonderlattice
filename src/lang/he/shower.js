<p>אנשים אמיתיים לא מגיבים באחידות כזאת, וברזים מערבלים אמיתיים לא משנים את הטמפרטורה באחידות כשמסובבים אותם. כאן המים עולים בצינור כמו גוש אחד, בלי להתערבב ובלי להתקרר. מעבר ל־⁦π/2⁩ התנודות של המשוואה גדלות בלי גבול; הקצוות של הברז, ב־⁦10 °C⁩ וב־⁦55 °C⁩, הופכים את הגדילה הזאת לתנודה קבועה ביניהם, כך שגודל התנודה שאתם רואים נקבע על ידי הקצוות, לא על ידי המשוואה. הרבה מערכות חימום ביתיות פשוט נדלקות ונכבות, וזה משהו שהחדר הזה לא מראה.</p>
